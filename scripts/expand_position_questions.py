conn = sqlite3.connect(DB_PATH)

# 确保 target_positions 列存在
ensure_column(conn)

TOTAL_BEFORE = conn.execute("SELECT COUNT(*) FROM questions").fetchone()[0]

all_questions = []
# AI工程师
for text, diff, source, level, tags, answer in ai_questions:
    all_questions.append((text, diff, "AI", "", source, level, tags, answer, "AI工程师"))
# 测试开发
for text, diff, source, level, tags, answer in test_questions:
    all_questions.append((text, diff, "测试", "", source, level, tags, answer, "测试开发"))
# 产品经理
for text, diff, source, level, tags, answer in pm_questions:
    all_questions.append((text, diff, "产品", "", source, level, tags, answer, "产品经理"))

# 记录来源分布和等级分布
source_dist = {}
level_dist = {}
pos_dist = {}
added_count = 0
skip_count = 0

for text, diff, category, company, source, level, tags, answer, position in all_questions:
    # 检查是否已存在
    exists = conn.execute(
        "SELECT id FROM questions WHERE question_text = ? AND scenario_id = ?",
        (text, SCENARIO_ID)
    ).fetchone()
    if exists:
        skip_count += 1
        continue

    # 判断 target_positions
    if position == "AI工程师":
        target_pos = ["AI工程师", "算法工程师"]
        src_type = "real_interview" if ("牛客" in source or "CSDN-大模型" in source or "GitHub" in source or "CSDN-深度" in source) else "open_source"
    elif position == "测试开发":
        target_pos = ["测试开发"]
        src_type = "real_interview" if ("牛客" in source or "腾讯云" in source) else "open_source"
    elif position == "产品经理":
        target_pos = ["产品经理"]
        src_type = "real_interview" if ("牛客" in source or "CSDN-大厂" in source) else "open_source"
    else:
        target_pos = [position]
        src_type = "real_interview"

    qid = add_question(conn, text, category, diff, company, position,
                       src_type, source, level, tags, answer, target_pos)
    if qid:
        added_count += 1
        source_dist[source] = source_dist.get(source, 0) + 1
        level_dist[level] = level_dist.get(level, 0) + 1
        pos_dist[position] = pos_dist.get(position, 0) + 1

TOTAL_AFTER = conn.execute("SELECT COUNT(*) FROM questions").fetchone()[0]
conn.close()

