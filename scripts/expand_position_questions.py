def ensure_column(conn):
    """Add target_positions column if not exists."""
    try:
        conn.execute("ALTER TABLE questions ADD COLUMN target_positions TEXT DEFAULT '[]'")
        conn.commit()
        print("  [migrate] 新增 target_positions 列")
    except sqlite3.OperationalError:
        pass  # 已存在


def add_question(conn, text, category, difficulty, company, position,
                 source_type, source, question_level, tags,
                 reference_answer, target_positions):
    """Insert a question, return question_id."""
    import uuid, datetime
    qid = str(uuid.uuid4())
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    target_pos_str = json.dumps(target_positions, ensure_ascii=False)
    try:
        conn.execute(
            """INSERT INTO questions
               (id, scenario_id, category, difficulty, question_text,
                reference_answer, tags, company, position, source,
                source_type, year, question_level, target_positions,
                created_at, updated_at)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (qid, SCENARIO_ID, category, difficulty, text,
             reference_answer, json.dumps(tags, ensure_ascii=False),
             company, position, source, source_type, "",
             question_level, target_pos_str, now, now)
        )
        conn.commit()
        return qid
    except Exception as e:
        print(f"  [ERROR] 入库失败: {e}")
        print(f"  题目: {text[:50]}")
        return None


